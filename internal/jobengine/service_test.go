func newTestAirports() []geo.Airport {
	// NYC area, Berlin area + nearby.
	return []geo.Airport{
		{IATA: "JFK", Name: "JFK", Location: geo.Point{Lat: 40.6398, Lng: -73.7789}},
		{IATA: "EWR", Name: "EWR", Location: geo.Point{Lat: 40.6925, Lng: -74.1687}},
		{IATA: "TXL", Name: "TXL", Location: geo.Point{Lat: 52.5597, Lng: 13.2877}},
		{IATA: "PRG", Name: "PRG", Location: geo.Point{Lat: 50.1008, Lng: 14.26}},
	}
}

func newTestGraph() routes.RouteGraph {
	g := routes.RouteGraph{
		"JFK": {"TXL": {}, "PRG": {}},
		"EWR": {"TXL": {}, "PRG": {}},
		"TXL": {"JFK": {}, "EWR": {}},
		"PRG": {"JFK": {}, "EWR": {}},
	}
	return g
}

func validRequest() SearchRequest {
	return SearchRequest{
		OriginLat:  40.6398,
		OriginLng:  -73.7789,
		OriginR:    100,
		DestLat:    52.36,
		DestLng:    13.50,
		DestR:      350,
		DepartFrom: "2026-10-15",
		DepartTo:   "2026-10-17",
	}
}

func TestService_GenerateTuples_FullCombinatorics(t *testing.T) {
	repo := &mockRepo{}
	enq := &mockEnqueuer{}
	svc := NewService(repo, &mockAirports{airports: newTestAirports(), graph: newTestGraph()}, enq)

	id, total, err := svc.Submit(context.Background(), validRequest())
	if err != nil {
		t.Fatalf("submit: %v", err)
	}
	if id == uuid.Nil {
		t.Fatal("expected non-nil id")
	}
	// 2 origins (JFK, EWR) x 2 destinations (BER, PRG) x 3 dates = 12
	if total != 12 {
		t.Errorf("total = %d, want 12 (2 origins x 2 dests x 3 dates)", total)
	}
	if len(enq.items) != 12 {
		t.Errorf("enqueued %d, want 12", len(enq.items))
	}
}

func TestService_TooManyPairsRejected(t *testing.T) {
	repo := &mockRepo{}
	enq := &mockEnqueuer{}
	svc := NewService(repo, &mockAirports{airports: newTestAirports(), graph: newTestGraph()}, enq)

	// Use a small max-pairs cap to force rejection.
	svc.maxPairs = 5

	_, total, err := svc.Submit(context.Background(), validRequest())
	if err == nil {
		t.Fatal("expected error, got nil")
	}
	if !errors.Is(err, ErrTooManyPairs) {
		t.Errorf("err = %v, want ErrTooManyPairs", err)
	}
	if total != 12 {
		t.Errorf("total = %d, want 12 (count should still be reported)", total)
	}
}

