func TestService_OriginAndDestOverlap(t *testing.T) {
	// When origin and dest circles overlap, the route graph still filters correctly.
	repo := &mockRepo{}
	enq := &mockEnqueuer{}
	airports := []geo.Airport{
		{IATA: "AAA", Name: "AAA", Location: geo.Point{Lat: 0, Lng: 0}},
		{IATA: "BBB", Name: "BBB", Location: geo.Point{Lat: 1, Lng: 1}},
	}
	graph := routes.RouteGraph{
		"AAA": {"BBB": {}},
		"BBB": {"AAA": {}},
	}
	svc := NewService(repo, &mockAirports{airports: airports, graph: graph}, enq)

	req := SearchRequest{
		OriginLat: 0, OriginLng: 0, OriginR: 200,
		DestLat: 0, DestLng: 0, DestR: 200,
		DepartFrom: "2026-10-15", DepartTo: "2026-10-15",
	}
	_, total, err := svc.Submit(context.Background(), req)
	if err != nil {
		t.Fatalf("submit: %v", err)
	}
	// Self-pairs (AAA, AAA) and (BBB, BBB) are excluded by GenerateAllPairs.
	if total != 2 {
		t.Errorf("total = %d, want 2 (AAA<->BBB both directions)", total)
	}
}

func TestValidateRequest(t *testing.T) {
	tests := []struct {
		name string
		req  SearchRequest
		want error
	}{
		{
			name: "valid",
			req:  validRequest(),
			want: nil,
		},
		{
			name: "origin lat out of range",
			req:  func() SearchRequest { r := validRequest(); r.OriginLat = 91; return r }(),
			want: ErrInvalidInput,
		},
		{
			name: "negative origin radius",
			req:  func() SearchRequest { r := validRequest(); r.OriginR = -1; return r }(),
			want: ErrInvalidInput,
		},
		{
			name: "destination radius too large",
			req:  func() SearchRequest { r := validRequest(); r.DestR = 99999; return r }(),
			want: ErrInvalidInput,
		},
		{
			name: "bad date format",
			req:  func() SearchRequest { r := validRequest(); r.DepartFrom = "10-15-2026"; return r }(),
			want: ErrInvalidInput,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			err := validateRequest(tt.req)
			if tt.want == nil && err != nil {
				t.Errorf("err = %v, want nil", err)
			} else if tt.want != nil && !errors.Is(err, tt.want) {
				t.Errorf("err = %v, want %v", err, tt.want)
			}
		})
	}
}

