type mockRepo struct {
	mu         sync.Mutex
	createdJob *SearchJob
	created    []SearchJobResult
	pending    map[uuid.UUID][]SearchJobResult
}

func (m *mockRepo) CreateJob(_ context.Context, job SearchJob, pairs []SearchJobResult) (uuid.UUID, error) {
	m.mu.Lock()
	defer m.mu.Unlock()
	if job.ID == uuid.Nil {
		job.ID = uuid.New()
	}
	m.createdJob = &job
	m.created = pairs
	if m.pending == nil {
		m.pending = make(map[uuid.UUID][]SearchJobResult)
	}
	m.pending[job.ID] = pairs
	// Assign IDs as if generated by DB.
	for i := range pairs {
		pairs[i].ID = int64(i + 1)
		pairs[i].JobID = job.ID
	}
	return job.ID, nil
}

func (m *mockRepo) GetJob(_ context.Context, id uuid.UUID) (SearchJob, error) {
	m.mu.Lock()
	defer m.mu.Unlock()
	if m.createdJob == nil || m.createdJob.ID != id {
		return SearchJob{}, ErrJobNotFound
	}
	return *m.createdJob, nil
}

